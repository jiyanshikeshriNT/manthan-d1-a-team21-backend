-- ReturnRight V2: return requests, items, photos, customer flags and the append-only audit log
-- (LLD §2). audit_log lives here (not V3) because every return transition is audited from Phase 4.
-- Must run unchanged on PostgreSQL 17 and H2 (MODE=PostgreSQL).

CREATE SEQUENCE rma_number_seq START WITH 100001 INCREMENT BY 1;

CREATE TABLE return_request (
    id                 UUID         PRIMARY KEY,
    rma_number         VARCHAR(20)  NOT NULL,
    order_id           BIGINT       NOT NULL,
    customer_id        BIGINT       NOT NULL,
    status             VARCHAR(30)  NOT NULL,
    refund_method      VARCHAR(20)  NOT NULL,
    flagged            BOOLEAN      NOT NULL,
    label_code         VARCHAR(64)  NOT NULL,
    client_request_key VARCHAR(160),
    total_refund_paise BIGINT,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    closed_at          TIMESTAMP WITH TIME ZONE,
    version            BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_return_request_rma UNIQUE (rma_number),
    CONSTRAINT uk_return_request_label UNIQUE (label_code),
    CONSTRAINT uk_return_request_client_key UNIQUE (client_request_key),
    CONSTRAINT fk_return_request_order FOREIGN KEY (order_id) REFERENCES customer_order (id),
    CONSTRAINT fk_return_request_customer FOREIGN KEY (customer_id) REFERENCES customer (id),
    CONSTRAINT ck_return_request_status CHECK (status IN ('REQUESTED', 'PENDING_REVIEW', 'APPROVED', 'IN_TRANSIT',
        'RECEIVED', 'INSPECTED', 'AWAITING_FINANCE', 'REFUND_IN_PROGRESS', 'REFUNDED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT ck_return_request_refund_method CHECK (refund_method IN ('ORIGINAL_PAYMENT', 'STORE_CREDIT')),
    CONSTRAINT ck_return_request_total CHECK (total_refund_paise IS NULL OR total_refund_paise >= 0)
);
CREATE INDEX idx_return_request_customer_created ON return_request (customer_id, created_at);
CREATE INDEX idx_return_request_status ON return_request (status);
CREATE INDEX idx_return_request_order ON return_request (order_id);

CREATE TABLE return_item (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_id       UUID        NOT NULL,
    order_line_id   BIGINT      NOT NULL,
    requested_qty   INT         NOT NULL,
    reason_code     VARCHAR(30) NOT NULL,
    reason_text     VARCHAR(500),
    condition_grade VARCHAR(1),
    decision        VARCHAR(10),
    accepted_qty    INT,
    refund_paise    BIGINT,
    inspection_note VARCHAR(500),
    CONSTRAINT uk_return_item_line UNIQUE (return_id, order_line_id),
    CONSTRAINT fk_return_item_return FOREIGN KEY (return_id) REFERENCES return_request (id),
    CONSTRAINT fk_return_item_order_line FOREIGN KEY (order_line_id) REFERENCES order_line (id),
    CONSTRAINT ck_return_item_qty CHECK (requested_qty > 0),
    CONSTRAINT ck_return_item_reason CHECK (reason_code IN ('DAMAGED', 'DEFECTIVE', 'WRONG_ITEM', 'WRONG_SIZE',
        'NOT_AS_DESCRIBED', 'CHANGED_MIND', 'OTHER')),
    CONSTRAINT ck_return_item_grade CHECK (condition_grade IS NULL OR condition_grade IN ('A', 'B', 'C')),
    CONSTRAINT ck_return_item_decision CHECK (decision IS NULL OR decision IN ('ACCEPTED', 'REJECTED')),
    CONSTRAINT ck_return_item_accepted CHECK (accepted_qty IS NULL OR (accepted_qty >= 0 AND accepted_qty <= requested_qty)),
    CONSTRAINT ck_return_item_refund CHECK (refund_paise IS NULL OR refund_paise >= 0)
);
CREATE INDEX idx_return_item_order_line ON return_item (order_line_id);

CREATE TABLE return_photo (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_item_id BIGINT      NOT NULL,
    stored_name    VARCHAR(64) NOT NULL,
    content_type   VARCHAR(20) NOT NULL,
    size_bytes     BIGINT      NOT NULL,
    CONSTRAINT uk_return_photo_stored_name UNIQUE (stored_name),
    CONSTRAINT fk_return_photo_item FOREIGN KEY (return_item_id) REFERENCES return_item (id),
    CONSTRAINT ck_return_photo_type CHECK (content_type IN ('image/jpeg', 'image/png')),
    CONSTRAINT ck_return_photo_size CHECK (size_bytes > 0 AND size_bytes <= 5242880)
);
CREATE INDEX idx_return_photo_item ON return_photo (return_item_id);

CREATE TABLE customer_flag (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  BIGINT NOT NULL,
    return_id    UUID   NOT NULL,
    return_count INT    NOT NULL,
    flagged_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    cleared_at   TIMESTAMP WITH TIME ZONE,
    cleared_by   VARCHAR(64),
    CONSTRAINT fk_customer_flag_customer FOREIGN KEY (customer_id) REFERENCES customer (id),
    CONSTRAINT fk_customer_flag_return FOREIGN KEY (return_id) REFERENCES return_request (id),
    CONSTRAINT ck_customer_flag_count CHECK (return_count > 0)
);
CREATE INDEX idx_customer_flag_customer ON customer_flag (customer_id);

-- Append-only: application code never updates or deletes rows (no update/delete in the repository).
CREATE TABLE audit_log (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type    VARCHAR(40)   NOT NULL,
    entity_id      VARCHAR(64)   NOT NULL,
    action         VARCHAR(40)   NOT NULL,
    from_state     VARCHAR(30),
    to_state       VARCHAR(30),
    actor          VARCHAR(100)  NOT NULL,
    actor_role     VARCHAR(20)   NOT NULL,
    details        VARCHAR(2000),
    correlation_id VARCHAR(64),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_audit_log_entity ON audit_log (entity_type, entity_id);
