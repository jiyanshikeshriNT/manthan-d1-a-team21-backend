-- ReturnRight V3: refunds, double-entry ledger, audit and dashboard indexes (LLD §2, ADR-001).
-- Must run unchanged on PostgreSQL 17 and H2 (MODE=PostgreSQL).

-- One refund per return (return_id UNIQUE) and one deterministic gateway key per refund.
CREATE TABLE refund (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_id         UUID         NOT NULL,
    amount_paise      BIGINT       NOT NULL,
    method            VARCHAR(20)  NOT NULL,
    status            VARCHAR(20)  NOT NULL,
    idempotency_key   VARCHAR(80)  NOT NULL,
    gateway_txn_id    VARCHAR(64),
    attempts          INT          NOT NULL DEFAULT 0,
    requires_approval BOOLEAN      NOT NULL,
    approved_by       VARCHAR(100),
    approved_at       TIMESTAMP WITH TIME ZONE,
    last_error        VARCHAR(500),
    next_attempt_at   TIMESTAMP WITH TIME ZONE,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    version           BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_refund_return UNIQUE (return_id),
    CONSTRAINT uk_refund_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT fk_refund_return FOREIGN KEY (return_id) REFERENCES return_request (id),
    CONSTRAINT ck_refund_amount CHECK (amount_paise > 0),
    CONSTRAINT ck_refund_method CHECK (method IN ('ORIGINAL_PAYMENT', 'STORE_CREDIT')),
    CONSTRAINT ck_refund_status CHECK (status IN ('PENDING', 'AWAITING_APPROVAL', 'PROCESSING', 'UNKNOWN',
        'SUCCEEDED', 'FAILED', 'REJECTED')),
    CONSTRAINT ck_refund_attempts CHECK (attempts >= 0)
);
CREATE INDEX idx_refund_status ON refund (status);

-- Append-only double-entry ledger. The UNIQUE key makes a second posting for a refund impossible.
CREATE TABLE ledger_entry (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_id    BIGINT      NOT NULL,
    customer_id  BIGINT      NOT NULL,
    account      VARCHAR(30) NOT NULL,
    direction    VARCHAR(6)  NOT NULL,
    amount_paise BIGINT      NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_ledger_entry_posting UNIQUE (refund_id, account, direction),
    CONSTRAINT fk_ledger_entry_refund FOREIGN KEY (refund_id) REFERENCES refund (id),
    CONSTRAINT ck_ledger_entry_account CHECK (account IN ('REFUND_EXPENSE', 'GATEWAY_CLEARING', 'STORE_CREDIT_LIABILITY')),
    CONSTRAINT ck_ledger_entry_direction CHECK (direction IN ('DEBIT', 'CREDIT')),
    CONSTRAINT ck_ledger_entry_amount CHECK (amount_paise > 0)
);
CREATE INDEX idx_ledger_entry_created ON ledger_entry (created_at);

-- Audit lookups by id alone (manager audit endpoint) and by time.
CREATE INDEX idx_audit_log_entity_id ON audit_log (entity_id);
CREATE INDEX idx_audit_log_created ON audit_log (created_at);

-- Manager dashboard aggregates (Phase 7).
CREATE INDEX idx_customer_order_ordered ON customer_order (ordered_at);
CREATE INDEX idx_return_request_created ON return_request (created_at);
CREATE INDEX idx_return_request_closed ON return_request (closed_at);
CREATE INDEX idx_customer_flag_active ON customer_flag (cleared_at, customer_id);
