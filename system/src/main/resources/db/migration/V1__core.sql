-- ReturnRight V1: core reference and order data (LLD §2).
-- Must run unchanged on PostgreSQL 17 and H2 (MODE=PostgreSQL). Money is BIGINT paise.

CREATE TABLE category (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code               VARCHAR(32)  NOT NULL,
    name               VARCHAR(100) NOT NULL,
    returnable         BOOLEAN      NOT NULL,
    return_window_days INT,
    CONSTRAINT uk_category_code UNIQUE (code),
    CONSTRAINT ck_category_window CHECK (return_window_days IS NULL OR return_window_days > 0)
);

CREATE TABLE product (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku         VARCHAR(32)  NOT NULL,
    name        VARCHAR(200) NOT NULL,
    category_id BIGINT       NOT NULL,
    price_paise BIGINT       NOT NULL,
    CONSTRAINT uk_product_sku UNIQUE (sku),
    CONSTRAINT fk_product_category FOREIGN KEY (category_id) REFERENCES category (id),
    CONSTRAINT ck_product_price CHECK (price_paise >= 0)
);
CREATE INDEX idx_product_category ON product (category_id);

CREATE TABLE customer (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email      VARCHAR(254) NOT NULL,
    name       VARCHAR(200) NOT NULL,
    phone      VARCHAR(20),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_customer_email UNIQUE (email),
    CONSTRAINT ck_customer_email_lower CHECK (email = LOWER(email))
);

CREATE TABLE customer_order (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number   VARCHAR(32) NOT NULL,
    customer_id    BIGINT      NOT NULL,
    ordered_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    delivered_at   TIMESTAMP WITH TIME ZONE,
    payment_method VARCHAR(20) NOT NULL,
    payment_ref    VARCHAR(64) NOT NULL,
    version        BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT uk_customer_order_number UNIQUE (order_number),
    CONSTRAINT fk_customer_order_customer FOREIGN KEY (customer_id) REFERENCES customer (id),
    CONSTRAINT ck_customer_order_payment_method
        CHECK (payment_method IN ('CARD', 'UPI', 'NETBANKING', 'WALLET')),
    CONSTRAINT ck_customer_order_delivery CHECK (delivered_at IS NULL OR delivered_at >= ordered_at)
);
CREATE INDEX idx_customer_order_customer ON customer_order (customer_id);

CREATE TABLE order_line (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id         BIGINT NOT NULL,
    product_id       BIGINT NOT NULL,
    quantity         INT    NOT NULL,
    unit_price_paise BIGINT NOT NULL,
    CONSTRAINT fk_order_line_order FOREIGN KEY (order_id) REFERENCES customer_order (id),
    CONSTRAINT fk_order_line_product FOREIGN KEY (product_id) REFERENCES product (id),
    CONSTRAINT ck_order_line_quantity CHECK (quantity > 0),
    CONSTRAINT ck_order_line_price CHECK (unit_price_paise >= 0)
);
CREATE INDEX idx_order_line_order ON order_line (order_id);

CREATE TABLE staff_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(64)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    CONSTRAINT uk_staff_user_username UNIQUE (username),
    CONSTRAINT ck_staff_user_role CHECK (role IN ('WAREHOUSE', 'FINANCE', 'MANAGER'))
);
