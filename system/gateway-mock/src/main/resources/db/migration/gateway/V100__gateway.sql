-- Mock gateway's own table (gw_ prefix). Portal code never queries it (ADR-002).
-- Must run on PostgreSQL 17 and H2 (MODE=PostgreSQL).

CREATE TABLE gw_payment (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key VARCHAR(80)  NOT NULL,
    amount_paise    BIGINT       NOT NULL,
    reference       VARCHAR(64),
    status          VARCHAR(20)  NOT NULL,
    txn_id          VARCHAR(64)  NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_gw_payment_key UNIQUE (idempotency_key),
    CONSTRAINT uk_gw_payment_txn UNIQUE (txn_id),
    CONSTRAINT ck_gw_payment_amount CHECK (amount_paise > 0),
    CONSTRAINT ck_gw_payment_status CHECK (status IN ('SUCCEEDED'))
);
